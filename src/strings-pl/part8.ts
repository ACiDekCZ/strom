/** Polish month names: genitive (with a day, "2 listopada 1890") and nominative (month and year, "listopad 1890"). */
const PL_MONTHS_GEN = ['stycznia', 'lutego', 'marca', 'kwietnia', 'maja', 'czerwca', 'lipca', 'sierpnia', 'września', 'października', 'listopada', 'grudnia'];
const PL_MONTHS_NOM = ['styczeń', 'luty', 'marzec', 'kwiecień', 'maj', 'czerwiec', 'lipiec', 'sierpień', 'wrzesień', 'październik', 'listopad', 'grudzień'];
/** A month given in the genitive, in the nominative (other strings as they are). */
const monthNomPl = (m: string): string => { const i = PL_MONTHS_GEN.indexOf(m); return i >= 0 ? PL_MONTHS_NOM[i] : m; };
/** A century in Roman numerals, as Polish writes it ("XIX wiek"); out of range as digits. */
function romanPl(n: number): string {
    if (!Number.isInteger(n) || n < 1 || n > 39) return String(n);
    const tens = ['', 'X', 'XX', 'XXX'][Math.floor(n / 10)];
    const ones = ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX'][n % 10];
    return tens + ones;
}

