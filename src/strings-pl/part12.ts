/** A count with Polish digit grouping and the word's form ("1 248 osób"). */
const cnt = (n: number, one: string, few: string, many: string): string => `${numPl(n)} ${plPl(n, one, few, many)}`;
const people = (n: number): string => cnt(n, 'osoba', 'osoby', 'osób');
