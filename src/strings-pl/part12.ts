const places = (n: number, level: 'town' | 'district' | 'country'): string => level === 'district' ? cnt(n, 'powiat', 'powiaty', 'powiatów')
    : level === 'country' ? cnt(n, 'kraj', 'kraje', 'krajów') : cnt(n, 'miejsce', 'miejsca', 'miejsc');

